const nicheIds = new Set(["cat-13", "cat-23", "cat-33", "cat-60", "cat-61"]);

export const CATEGORIES: Category[] = names
  .map((name, i) => {
    const id = `cat-${i + 1}`;
    return {
      id,
      name,
      emoji: emojis[i] ?? "❔",
      color: ["#ff6b35", "#35c2a6", "#7c6cff", "#e6b84b"][i % 4],
      niche: nicheIds.has(id),
    };
  })
  .sort((a, b) => Number(a.niche) - Number(b.niche));

export const DEFAULT_CATEGORIES = CATEGORIES.filter(
  (category) => !category.niche,
);
export const categoryById = (id: string) => CATEGORIES.find((c) => c.id === id);

